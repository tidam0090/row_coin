  code TEXT PRIMARY KEY,
  kind TEXT NOT NULL CHECK (kind IN ('deposit', 'withdrawal')),
  title TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  primary_label TEXT NOT NULL DEFAULT '',
  primary_value TEXT NOT NULL DEFAULT '',
  secondary_label TEXT NOT NULL DEFAULT '',
  secondary_value TEXT NOT NULL DEFAULT '',
  note_label TEXT NOT NULL DEFAULT '',
  note_value TEXT NOT NULL DEFAULT '',
  input_label TEXT NOT NULL DEFAULT '',
  input_placeholder TEXT NOT NULL DEFAULT '',
  qr_code_url TEXT NOT NULL DEFAULT '',
